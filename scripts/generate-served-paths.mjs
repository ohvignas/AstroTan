#!/usr/bin/env node
// Writes the list of paths the Astro site serves from its own route files.
//
// This is the third source of truth a redirect has to check against, and
// the one the first attempt at lot 4 missed. A designed page is neither a
// published row nor a prerendered path: it is an `.astro` file with
// `prerender = false`, whose `pages` row may not exist yet. A redirect
// claiming its path would shadow it with no guard firing, because the
// middleware runs before the route.
//
// Generated, never hand-kept: a hand-written list diverges at the second
// page, and the divergence is silent — which is exactly the class of bug
// this file exists to prevent.
//
//   node scripts/generate-served-paths.mjs
//
// Run by the `predev`/`prebuild` hooks of `apps/web`, so it cannot drift
// from the routes it describes.

import { readdir, writeFile } from "node:fs/promises"
import { join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = fileURLToPath(new URL("..", import.meta.url))
const PAGES_DIR = join(ROOT, "apps/web/src/pages")
const OUT = join(ROOT, "packages/backend/convex/lib/servedPaths.generated.ts")

async function walk(dir) {
  const found = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    // Astro excludes anything under `src/pages` prefixed with `_` from
    // routing — `api/_tests/` is exactly that, and must not appear here.
    if (entry.name.startsWith("_")) continue
    const full = join(dir, entry.name)
    if (entry.isDirectory()) found.push(...(await walk(full)))
    else if (entry.name.endsWith(".astro")) found.push(full)
  }
  return found
}

const files = await walk(PAGES_DIR)

const exact = new Set()
const prefixes = new Set()

for (const file of files) {
  const route = relative(PAGES_DIR, file).replace(/\.astro$/, "")
  // A dynamic segment cannot become an exact path: `blog/[slug]` serves
  // every `/blog/<something>`, so it contributes a prefix instead.
  const dynamicAt = route.split("/").findIndex((s) => s.includes("["))
  if (dynamicAt === -1) {
    exact.add("/" + route.replace(/\/?index$/, ""))
  } else {
    const prefix = route.split("/").slice(0, dynamicAt).join("/")
    prefixes.add("/" + prefix)
  }
}

const body = `// GENERATED by scripts/generate-served-paths.mjs — do not edit.
//
// The paths this site's own route files answer on. See the generator for
// why this is generated rather than written by hand, and why a redirect
// has to check it.

/** Paths a route file serves exactly. */
export const SERVED_PATHS: readonly string[] = ${JSON.stringify([...exact].sort(), null, 2)}

/** Prefixes a dynamic route serves everything under. */
export const SERVED_PREFIXES: readonly string[] = ${JSON.stringify([...prefixes].sort(), null, 2)}
`

await writeFile(OUT, body)
console.log(
  `servedPaths: ${exact.size} exact, ${prefixes.size} prefix(es) → ${relative(ROOT, OUT)}`
)
